package com.wt.airconditioner;

import android.view.View;

/**
 * Контракт вкладки: получить свою страницу и перекраситься под тему.
 *
 * Обе операции и раньше были у всех четырёх контроллеров с этими же
 * сигнатурами — MainActivity перечисляла их двумя switch по позиции вкладки.
 * Разъехавшись, эти таблицы дали бы вкладку, которую забыли покрасить или
 * привязать, причём молча: пятая вкладка просто осталась бы пустой.
 */
interface TabController {

    /** Страница создана адаптером: разовая привязка View и слушателей. */
    void bind(View page);

    /** Сменилась тема — или страница только что создана и красится впервые. */
    void applyTheme(ThemePalette palette);

    /**
     * Вкладка вышла на экран или ушла с него — приходит всем вкладкам на каждое
     * переключение, а не одной показанной: логу нужны оба края, он копит текст
     * молча, пока не виден.
     *
     * Раньше это была третья таблица по позициям в Activity: она знала, что
     * пресетам нужен render, а настройкам — проверка обновления. Знание о том,
     * что вкладке делать при показе, принадлежит самой вкладке.
     */
    void onTabVisible(boolean visible);
}
