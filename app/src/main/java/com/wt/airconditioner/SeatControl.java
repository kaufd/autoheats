package com.wt.airconditioner;

/**
 * Что вкладка сидений вправе сделать с сервисом: спросить состояние сиденья и
 * сменить его режим или уровень.
 *
 * Роль, а не весь сервис: диагностические кнопки, редактирование пресетов и
 * переподключение к Car сюда не входят — вкладка сидений о них не знает.
 *
 * applyActivePreset здесь потому, что «Пресеты» — один из трёх режимов
 * переключателя на этой вкладке: выбор режима обязан вернуть сиденье под
 * прошлое расписание, а не открывать редактор.
 */
interface SeatControl {

    /**
     * Лучшая известная оценка уровня: подтверждённое значение этой сессии,
     * иначе прошлой. Точного ответа не существует — свойство подогрева может
     * быть недоступно на чтение.
     */
    int levelOf(Seat seat);

    HeatMode modeOf(Seat seat);

    void setMode(Seat seat, HeatMode mode);

    /** false — автомобиль команду не принял; экран не должен обещать тепло. */
    boolean setManualLevel(Seat seat, int level);

    /** false — повторять нечего: пресет не выбирали или его удалили. */
    boolean applyActivePreset(Seat seat);
}
