package com.wt.airconditioner;

/**
 * Куда уходит диагностическая строка. Свой тип, а не вложенный в движок
 * каскада: его пишут и каскад, и фоновая модель, и ряд калибровки — классы,
 * которые больше ничем друг с другом не связаны.
 *
 * В тестах обычно не нужен: сервис подаёт сюда LogBuffer, тесты — null или
 * список.
 */
interface LogSink {
    void log(String message);
}
