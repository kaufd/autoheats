package com.wt.airconditioner;

/**
 * Поездка глазами приложения: было ли зажигание и выключены ли сиденья.
 *
 * Ни одной ссылки на Android, поэтому решения проверяются тестом на JVM. Иначе
 * их не проверить: лестница ACC → OFF, пробуждение головы и перезапуск сервиса
 * воспроизводятся только в машине, а ошибка здесь тихая — либо подогрев гаснет
 * у человека под руками, либо остаётся включённым в брошенной машине.
 */
final class IgnitionSession {

    /** Что сервис должен сделать по событию зажигания. */
    enum Action {
        NOTHING,
        START_HEAT,
        SHUTDOWN
    }

    /**
     * Зажигание уже было ON — машина ехала, и следующее «не ON» означает конец
     * поездки.
     *
     * ГУ стартует от открытия водительской двери, задолго до зажигания, и
     * подогрев в этот момент уже физически работает (проверено на машине:
     * сиденья греют при выключенном зажигании). Без флага первое же «не ON»
     * гасило бы подогрев, включённый пока человек садится.
     */
    private boolean sawIgnitionOn;

    /**
     * Сиденья подтверждённо выключены. Голова отдаёт выключение лестницей ACC →
     * OFF, и без флага каждая ступень повторяла бы уже выполненное выключение.
     *
     * На старте true, и это не догадка: подогрев запитан от ГУ и гаснет вместе с
     * ним. Иначе сервис, перезапущенный при живом ГУ в ACC (START_STICKY,
     * обновление, краш), погасил бы подогрев, которым водитель пользуется.
     */
    private boolean seatsOff = true;

    Action onIgnition(boolean on) {
        if (on) {
            if (sawIgnitionOn) {
                return Action.NOTHING;
            }
            sawIgnitionOn = true;
            return Action.START_HEAT;
        }
        if (!sawIgnitionOn) {
            /**
             * Машину ещё не заводили: ГУ подняли открытием двери, человек
             * садится, и подогрев уже может работать.
             */
            return Action.NOTHING;
        }
        if (seatsOff) {
            /**
             * ACC → OFF идут одно за другим: второе выключение ничего не меняет.
             */
            return Action.NOTHING;
        }
        return Action.SHUTDOWN;
    }

    /**
     * Подтверждённое выключение закрывает поездку: на заправке двигатель глушат
     * и через три минуты заводят снова, и это повторное ON обязано запустить
     * каскад заново.
     *
     * Неподтверждённое оставляет поездку открытой: следующая ступень ACC → OFF
     * должна получить право повторить попытку.
     */
    void shutdownResult(boolean confirmed) {
        seatsOff = confirmed;
        if (confirmed) {
            sawIgnitionOn = false;
        }
    }

    /** Сиденье греет — значит, выключенными они больше не считаются. */
    void seatsHeating() {
        seatsOff = false;
    }

    /**
     * Короткая стоянка: процесс жив, но в машину сели заново, поэтому сессия
     * начинается с нуля — иначе первое же «не ON» после пробуждения сочли бы
     * концом старой поездки, и автоподогрев не запустился бы вовсе.
     */
    void onWakeUp() {
        sawIgnitionOn = false;
        seatsOff = true;
    }
}
