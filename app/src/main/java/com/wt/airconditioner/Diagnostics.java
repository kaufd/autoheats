package com.wt.airconditioner;

/**
 * Что вкладка логов вправе сделать с сервисом: писать в общий буфер (LogSink) и
 * запускать отладочные действия. Управление подогревом сюда не входит.
 *
 * Роль, а не весь сервис: на голове нет adb, поэтому проверять расписание,
 * соединение и реакцию на температуру приходится кнопками, — но это единственная
 * причина, по которой вкладка диагностики вообще держит ссылку на сервис.
 * Получая {@code SeatHeatService} целиком, она могла бы и греть сиденья.
 */
interface Diagnostics extends LogSink {

    /** Чистит источник лога, а не только его представление в Activity. */
    void clearLogs();

    /** Разовое чтение температуры салона; результат придёт строкой лога. */
    void readCabinTemperature();

    /**
     * Температура вместо датчика: иначе каскад проверяется только зимой и
     * только в поездке.
     */
    void injectTemperature(double celsius);

    /**
     * Запуск каскада руками: обычный триггер — зажигание ON, а он бывает раз в
     * поездку и только в холод.
     */
    void startAutoHeatNow();

    /** Рвёт связь с Car и поднимает заново: сам CarService на голове не перезапустить. */
    void restartCarConnection();
}
