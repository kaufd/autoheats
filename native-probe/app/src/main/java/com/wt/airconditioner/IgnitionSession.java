package com.wt.airconditioner;

/**
 * Поездка глазами приложения: было ли зажигание и выключены ли сиденья.
 *
 * Вынесено из сервиса по той же причине, что и AutoHeatEngine: ни одной ссылки
 * на Android, поэтому решения проверяются тестом на JVM. Проверить их иначе
 * нельзя — лестница состояний ACC → OFF, пробуждение головы и перезапуск
 * сервиса воспроизводятся только в машине, а ошибка здесь тихая: либо подогрев
 * гаснет у человека под руками, либо остаётся включённым в брошенной машине.
 */
final class IgnitionSession {

    /** Что сервис должен сделать по событию зажигания. */
    enum Action {
        NOTHING,
        START_HEAT,
        SHUTDOWN
    }

    /**
     * В этой сессии зажигание уже было ON — то есть машина ехала, и следующее
     * «не ON» означает конец поездки.
     *
     * ГУ на этой голове стартует от открытия водительской двери, задолго до
     * зажигания, и подогрев в этот момент уже физически работает (проверено на
     * машине: сиденья греют при выключенном зажигании). Без этого флага первое
     * же событие «не ON» гасило бы подогрев, включённый пока человек садится,
     * — ровно то, ради чего приложение и существует.
     */
    private boolean sawIgnitionOn;

    /**
     * Сиденья подтверждённо выключены. Голова отдаёт выключение зажигания
     * лестницей состояний (ACC → OFF), и без этого флага каждая ступень
     * повторяла бы уже выполненное выключение, забивая лог дублями.
     *
     * На старте — true, и это не догадка: подогрев запитан от ГУ и гаснет
     * вместе с ним, так что к моменту запуска сервиса сиденья заведомо
     * выключены. Иначе сервис, перезапущенный при живом ГУ в ACC
     * (START_STICKY, обновление, краш), погасил бы подогрев, который водитель
     * включил сам и продолжает им пользоваться.
     */
    private boolean seatsOff = true;

    Action onIgnition(boolean on) {
        if (on) {
            if (sawIgnitionOn) {
                return Action.NOTHING;
            }
            sawIgnitionOn = true;
            return Action.START_HEAT;
        }
        if (!sawIgnitionOn) {
            // Машину ещё не заводили: ГУ подняли открытием двери, человек
            // садится. Подогрев в этот момент уже может работать — гасить его
            // здесь значит ломать то, ради чего приложение и нужно.
            return Action.NOTHING;
        }
        if (seatsOff) {
            // ACC → OFF идут одно за другим; второе выключение ничего не
            // меняет, только прячет в логе то, что важно.
            return Action.NOTHING;
        }
        return Action.SHUTDOWN;
    }

    /**
     * Чем кончилось выключение сидений. Подтверждённое закрывает поездку: на
     * заправке человек глушит двигатель и через три минуты заводит снова, и
     * это повторное ON обязано запустить каскад заново — иначе сиденья,
     * погашенные предыдущим OFF, останутся холодными до конца пути.
     *
     * Неподтверждённое, наоборот, оставляет поездку открытой: следующая
     * ступень лестницы ACC → OFF должна получить право повторить попытку.
     */
    void shutdownResult(boolean confirmed) {
        seatsOff = confirmed;
        if (confirmed) {
            sawIgnitionOn = false;
        }
    }

    /** Сиденье греет — значит, выключенными они больше не считаются. */
    void seatsHeating() {
        seatsOff = false;
    }

    /**
     * Голова проснулась после сна. Короткая стоянка: процесс жив, но в машину
     * сели заново, поэтому сессия начинается с нуля — иначе первое же «не ON»
     * после пробуждения сочли бы концом старой поездки, а автоподогрев, когда
     * он появится, не запустился бы вовсе.
     */
    void onWakeUp() {
        sawIgnitionOn = false;
        seatsOff = true;
    }
}
